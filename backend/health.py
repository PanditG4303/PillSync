"""Health Monitoring — manual vitals tracking, trends and AI insights.

Supports: weight, height, BMI, blood pressure, sugar level, heart rate,
blood oxygen, temperature, sleep hours, water intake, daily steps and mood.

BMI is computed on the fly from the latest height and weight entries.
AI insights are generated by Nemotron through the shared AI service and
degrade to a rule-based fallback when AI is unavailable.
"""

